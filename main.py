def verify_api6(name, sfz, max_retries=3):
    """
    中意财险二要素核验 —— 预热+直连混合版
    ★ 不再内部自动预热 —— 预热由外部在"开始核验前"完成（用真实name/sfz）
    ★ 如果意外没预热，第一次空响应时会自动预热一次兜底
    ★ 预热后直连，速度和原直连版一样快
    ★ 直连失败时自动重新预热再试（Session过期恢复）
    ★ 其他接口①②③④⑤完全不受影响
    ★ 成功判定（与源码一致）：
        - status==1 且 message=="成功"           → 匹配 ✅
        - "未配置销售人员信息" in message        → 匹配 ✅
        - "二要素不一致" / "请核对您的信息"      → 不匹配 ❌
        - 其他 / 异常 / 空响应                  → None（计入错误）
    """
    global _INS6_SESSION_ARMED
    last_msg = ""

    # ===== 如果意外没预热，兜底：用真实数据预热一次 =====
    if not _INS6_SESSION_ARMED:
        print(f"  {Color.YELLOW}⚠️ 接口⑥未预热，先用当前身份证预热...{Color.RESET}")
        _ins6_warmup_session(name, sfz, force=True)

    for attempt in range(1, max_retries + 1):
        try:
            # ========== 直连：不使用任何代理 ==========
            _saved_opener = urllib.request._opener
            urllib.request.install_opener(urllib.request.build_opener())

            req_data = _ins6_build_req(name, sfz)
            plaintext = json.dumps(req_data, ensure_ascii=False, separators=(",", ":"))
            encrypted_data = _ins6_aes_encrypt(plaintext)

            headers = _ins6_get_header()
            body = json.dumps({"encryptInfo": encrypted_data}, separators=(",", ":")).encode("utf-8")

            req = urllib.request.Request(
                _INS6_API_URL, data=body, headers=headers, method="POST"
            )

            t0 = time.time()
            with urllib.request.urlopen(
                req, context=ssl._create_unverified_context(), timeout=_INS6_REQUEST_TIMEOUT
            ) as resp:
                resp_text = resp.read().decode("utf-8")
            cost = (time.time() - t0) * 1000.0

            if _saved_opener:
                urllib.request.install_opener(_saved_opener)

            # 空响应
            if not resp_text or not resp_text.strip():
                last_msg = "空响应"
                # 可能是 Session 过期，尝试重新预热一次
                if attempt == 1:
                    print(f"  {Color.YELLOW}⚠️ 接口⑥空响应，尝试重新预热...{Color.RESET}")
                    _INS6_SESSION_ARMED = False
                    if _ins6_warmup_session(force=True):
                        continue  # 预热成功，重试当前 attempt
                if attempt < max_retries:
                    time.sleep(0.5)
                    continue
                _api_report_error(6)
                return None, f"空响应 [直连]", None, cost

            # 尝试直接 JSON 解析（明文）
            try:
                resp_json = json.loads(resp_text)
            except json.JSONDecodeError:
                try:
                    resp_json = _ins6_aes_decrypt(resp_text.strip())
                except Exception as dec_err:
                    last_msg = f"非JSON且解密失败:{str(dec_err)[:20]}"
                    # Session 可能过期，预热一次再试
                    if attempt == 1:
                        _INS6_SESSION_ARMED = False
                        if _ins6_warmup_session(force=True):
                            continue
                    if attempt < max_retries:
                        time.sleep(0.5)
                        continue
                    _api_report_error(6)
                    return None, f"非JSON响应 [直连]", None, cost

            # ===== 成功判定（严格对照源码） =====
            status = resp_json.get("status")
            raw_msg = resp_json.get("message", "") or ""
            msg = _ins6_clean_msg(raw_msg)

            # ① status==1 且 message=="成功" → 成功
            if status == 1 and msg == "成功":
                _api_report_success(6)
                return True, f"匹配 [中意财险] {msg} [直连]", resp_json, cost

            # ② "未配置销售人员信息" → 也算成功
            if "未配置销售人员信息" in msg:
                _api_report_success(6)
                return True, f"匹配 [中意财险] {msg} [直连]", resp_json, cost

            # ③ 明确不匹配
            if "二要素不一致" in msg or "请核对您的信息" in raw_msg or "保证姓名和身份证实际一致" in raw_msg:
                _api_report_success(6)
                return False, f"不匹配 [中意财险] {raw_msg[:60]} [直连]", resp_json, cost

            # ④ 其他情况：可能是 Session 过期
            last_msg = msg or f"status={status}"
            # 第一次遇到不明响应，尝试预热后重试一次
            if attempt == 1 and ("会话" in last_msg or "登录" in last_msg or "session" in last_msg.lower() or "expire" in last_msg.lower()):
                _INS6_SESSION_ARMED = False
                print(f"  {Color.YELLOW}⚠️ 接口⑥疑似Session过期，重新预热...{Color.RESET}")
                if _ins6_warmup_session(force=True):
                    continue
            if attempt < max_retries:
                time.sleep(0.5)
                continue
            _api_report_error(6)
            return None, f"未知 [中意财险] {last_msg[:40]} [直连]", resp_json, cost

        except urllib.error.HTTPError as e:
            try:
                if _saved_opener:
                    urllib.request.install_opener(_saved_opener)
            except Exception:
                pass
            # 401/403 通常是 Session 过期
            if e.code in (401, 403) and attempt == 1:
                _INS6_SESSION_ARMED = False
                print(f"  {Color.YELLOW}⚠️ 接口⑥ HTTP{e.code}，重新预热...{Color.RESET}")
                if _ins6_warmup_session(force=True):
                    continue
            last_msg = f"HTTP{e.code}"
            if attempt < max_retries:
                time.sleep(0.5)
                continue
            _api_report_error(6)
            return None, f"HTTP {e.code} [直连]", None, 0
        except Exception as e:
            try:
                if _saved_opener:
                    urllib.request.install_opener(_saved_opener)
            except Exception:
                pass
            # 连接错误可能是 Session/Cookie 失效导致服务端关闭连接
            err_str = str(e)[:40]
            if attempt == 1 and any(k in err_str.lower() for k in ("connection", "reset", "broken", "unauthorized", "forbidden")):
                _INS6_SESSION_ARMED = False
                print(f"  {Color.YELLOW}⚠️ 接口⑥异常({err_str})，重新预热...{Color.RESET}")
                if _ins6_warmup_session(force=True):
                    continue
            last_msg = err_str
            if attempt < max_retries:
                time.sleep(0.3)
                continue
            _api_report_error(6)
            return None, f"{err_str} [直连]", None, 0

    _api_report_error(6)
    return None, f"超过重试次数 [中意财险] {last_msg[:30]} [直连]", None, 0


