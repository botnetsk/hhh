from Crypto.Cipher import AES as _AES5
from Crypto.Util.Padding import pad as _pad5

def _api5_aes_enc(plain_text: str, key_str: str) -> str:
    """AES-ECB 加密，返回大写 hex"""
    key = key_str.encode("utf-8")
    data = plain_text.encode("utf-8")
    cipher = _AES5.new(key, _AES5.MODE_ECB)
    ct = cipher.encrypt(_pad5(data, _AES5.block_size))
    return ct.hex().upper()

def _build_api5_body(name: str, sfz: str) -> str:
    inner = json.dumps(
        {"name": name, "papersType": "1", "papersNumber": sfz, "nation": "CHN"},
        ensure_ascii=False, separators=(",", ":")
    )
    params = _api5_aes_enc(inner, AES_KEY_5)
    return urllib.parse.urlencode({"params": params, "appmark": APP_MARK_5})

def _parse_api5_response(data_obj):
    """判定赣服通响应：成功/匹配/失败"""
    if not isinstance(data_obj, dict):
        return None, f"失败[非dict]"
    code = str(data_obj.get("code", ""))
    msg  = str(data_obj.get("msg", "") or data_obj.get("message", ""))
    raw  = f"code={code} msg={msg[:30]}"

    # 成功关键字
    if code in ("0", "200", "00") or any(k in msg for k in ("成功", "通过", "一致", "认证成功")):
        return True, f"匹配 [原始: {raw}]"
    # 明确不匹配
    if any(k in msg for k in ("不匹配", "不一致", "姓名", "不存在", "失败", "错误")):
        return False, f"不匹配 [原始: {raw}]"
    # data 里可能嵌套
    inner = data_obj.get("data")
    if isinstance(inner, dict):
        inner_msg = str(inner.get("msg", "") or inner.get("message", ""))
        inner_code = str(inner.get("code", "") or inner.get("resultCode", ""))
        if inner_code in ("0", "200") or any(k in inner_msg for k in ("成功", "一致")):
            return True, f"匹配 [原始: {raw} data_ok]"
        if any(k in inner_msg for k in ("不匹配", "不一致")):
            return False, f"不匹配 [原始: {raw} data_fail]"
    return None, f"未知 [原始: {raw}]"

