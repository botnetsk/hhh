def generate_possible_ids(card, input_gender=None):
    norm = card.lower()
    if len(norm) != 18:
        print("错误: 身份证号码长度不正确! 必须是18位"); return []

    addr_p = norm[:6]; year_p = norm[6:10]; mon_p = norm[10:12]
    day_p = norm[12:14]; seq_p = norm[14:17]; chk_p = norm[17]

    if 'x' in addr_p:
        al = list(address_lookup(addr_p))
        if not al: print("未找到匹配的地区码"); return []
        print(f"地区: 匹配到 {len(al)} 个地区")
    else:
        al = [addr_p]; print(f"地区: {diquma.get(addr_p, '未知地区')}")

    if 'x' in year_p:
        while True:
            try:
                yi = input("请输入年份范围(格式:1990-1999): ").strip()
                if re.match(r'^\d{4}-\d{4}$', yi):
                    s_y, e_y = map(int, yi.split('-'))
                    if 1950 <= s_y <= e_y <= 2026:
                        yr = (s_y, e_y); break
                print("年份范围无效 请确保在1950-2026之间")
            except: print("请输入有效的数字")
    else:
        yr = (int(year_p), int(year_p))

    mon_d = []
    for i, c in enumerate(mon_p):
        mon_d.append(['0','1'] if (c=='x' and i==0) else (list('0123456789') if c=='x' else [c]))
    day_d = []
    for i, c in enumerate(day_p):
        day_d.append(['0','1','2','3'] if (c=='x' and i==0) else (list('0123456789') if c=='x' else [c]))

    gender = get_gender_from_seq(seq_p, input_gender)
    seq_d = []
    for i, c in enumerate(seq_p):
        if c == 'x':
            seq_d.append(['1','3','5','7','9'] if (i==2 and gender=='男') else (['0','2','4','6','8'] if (i==2 and gender=='女') else list('0123456789')))
        else:
            seq_d.append([c])

    total = len(al)*(yr[1]-yr[0]+1)*len(list(itertools.product(*mon_d)))*len(list(itertools.product(*day_d)))*len(list(itertools.product(*seq_d)))
    print(f"估算总组合数: {total}")
    print("开始生成有效身份证号码...")

    valid = set()
    st = time.time()
    with tqdm(total=total, desc="生成", unit="个", colour='Yellow') as pbar:
        for ad in al:
            for y in range(yr[0], yr[1]+1):
                ys = str(y)
                for mc in itertools.product(*mon_d):
                    ms = ''.join(mc); mi = int(ms)
                    if mi < 1 or mi > 12:
                        pbar.update(len(list(itertools.product(*day_d)))*len(list(itertools.product(*seq_d)))); continue
                    if mi in {4,6,9,11}: max_d = 30
                    elif mi == 2:
                        leap = (y%4==0 and y%100!=0) or (y%400==0)
                        max_d = 29 if leap else 28
                    else: max_d = 31
                    for dc in itertools.product(*day_d):
                        ds = ''.join(dc); di = int(ds)
                        if di < 1 or di > max_d:
                            pbar.update(len(list(itertools.product(*seq_d)))); continue
                        for sc in itertools.product(*seq_d):
                            ss = ''.join(sc); f17 = ad+ys+ms+ds+ss
                            cd = calculate_check_digit(f17)
                            if cd is None or (chk_p != 'x' and cd.upper() != chk_p.upper()):
                                pbar.update(1); continue
                            valid.add(f17+cd); pbar.update(1)

    print(f"生成耗时: {time.time()-st:.2f} 秒")
    # ★ 生成结果过滤（空行修复）
    valid = [s for s in valid if s and len(s) == 18]
    if valid:
        with open("sfz.txt","w",encoding="utf-8") as f:
            for x in valid: f.write(x+"\n")
        print(f"🟢 已自动保存 {len(valid)} 条至 sfz.txt")
    return list(valid) if valid else []

