def parse_api3_response(data_obj):
    if not isinstance(data_obj, dict):
        return False, f"失败 [原始: 返回不是dict: {str(data_obj)[:50]}]"
    success = data_obj.get("success")
    code = data_obj.get("code")
    ret  = data_obj.get("ret")
    msg = str(data_obj.get("msg", ""))
    inner = data_obj.get("data") if isinstance(data_obj.get("data"), dict) else {}
    dcode = inner.get("code")
    body = str(inner.get("body", ""))
    msg_lower = msg.lower()
    msg_short = msg[:40]

    outer_ok = ret if ret is not None else code
    code_str = str(outer_ok) if outer_ok is not None else ""
    raw = f"success={success} ret={code_str} dcode={dcode} msg={msg_short}"

    if success and str(outer_ok) in ("1", "0"):
        if dcode == 0 and "errcode" in body:
            m = re.search(r'errcode\?[:=]\?(\d+)', body.replace(" ", ""))
            if m and m.group(1) == "0":
                return True, f"匹配 [原始: {raw}]"
            if dcode == 0:
                return True, f"匹配 [原始: {raw}]"
    if code_str == "0" or "成功" in msg or "通过" in msg:
        return True, f"匹配 [原始: {raw}]"

    if success is False or code_str == "-1":
        return False, f"不匹配 [原始: {raw}]"
    for kw in _FAIL_KEYWORDS:
        if kw.lower() in msg_lower:
            return False, f"不匹配 [原始: {raw}]"
    if dcode and dcode != 0:
        return False, f"不匹配 [原始: {raw}]"
    if success is True:
        return False, f"不确定/失败 [原始: {raw}]"
    return False, f"失败 [原始: {raw}]"


