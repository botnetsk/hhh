class Throttle:
    enabled        = False
    delay_ms       = 100
    per_round_step = 150
    max_delay_ms   = 5000
    strikes        = 0
    penalty_per    = 200

    @classmethod
    def configure(cls, start, step, mx):
        cls.enabled = True
        cls.delay_ms = max(0, int(start))
        cls.per_round_step = max(0, int(step))
        cls.max_delay_ms = max(cls.delay_ms, int(mx))
        cls.strikes = 0
        print(f"  {Color.CYAN}🐢 减速已启用: 起始={cls.delay_ms}ms 每轮+{cls.per_round_step}ms 封顶={cls.max_delay_ms}ms{Color.RESET}")

    @classmethod
    def wait(cls):
        if not cls.enabled or cls.delay_ms <= 0:
            return
        time.sleep(cls.delay_ms / 1000.0)

    @classmethod
    def on_error(cls):
        if not cls.enabled:
            return
        cls.strikes += 1
        add = cls.penalty_per * cls.strikes
        cls.delay_ms = min(cls.max_delay_ms, cls.delay_ms + add)
        print(f"  {Color.MAGENTA}⚠️ 接口异常x{cls.strikes}，延迟升至 {cls.delay_ms}ms{Color.RESET}")

    @classmethod
    def on_success(cls):
        if not cls.enabled:
            return
        if cls.strikes > 0:
            cls.strikes = 0

    @classmethod
    def next_round(cls):
        if not cls.enabled:
            return
        new_delay = min(cls.max_delay_ms, cls.delay_ms + cls.per_round_step)
        if new_delay != cls.delay_ms:
            cls.delay_ms = new_delay

    @classmethod
    def reset(cls):
        cls.strikes = 0

