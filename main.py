def _ins6_clean_msg(msg: str) -> str:
    """
    与源码 clean_msg 一致，并额外识别中意财险特有的"不匹配"措辞。
    - "请核对您的信息，保证姓名和身份证实际一致" → 标准化为 "二要素不一致"
    - 其他情况保持原样，让上层判定逻辑能正确识别
    """
    if not msg:
        return ""
    # 标准化中意财险的"不匹配"提示（它不用"二要素不一致"这个标准措辞）
    if "请核对您的信息" in msg or "保证姓名和身份证实际一致" in msg:
        return "二要素不一致"
    prefixes = ["投保人:", "投保人：", "投保人: "]
    for p in prefixes:
        if msg.startswith(p):
            return msg[len(p):]
    return msg

