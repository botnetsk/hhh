# 坏代理黑名单（运行时动态添加，不持久化）
_PROXY_BAD = set()
_PROXY_LOCK = threading.Lock()
_PROXY_USED_TOTAL = 0  # 累计使用次数
_PROXY_FAIL_TOTAL = 0  # 累计失败次数

# 线程局部：记录当前线程正在使用的代理字符串（供 worker 打印）
_thread_local = threading.local()

def _proxy_pick():
    """随机挑一条可用代理，返回 (ip:port 字符串, http_proxy_url, https_proxy_url)"""
    global _PROXY_USED_TOTAL
    with _PROXY_LOCK:
        candidates = [p for p in _PROXY_LIST if p not in _PROXY_BAD]
    if not candidates:
        with _PROXY_LOCK:
            _PROXY_BAD.clear()
        candidates = list(_PROXY_LIST)
        print(f"  {Color.YELLOW}🟡 代理池重置: 黑名单已清空，重新启用全部 {len(candidates)} 条{Color.RESET}")
    p = _rand.choice(candidates)
    _PROXY_USED_TOTAL += 1
    # 写入线程局部，供外部打印
    _thread_local.current_proxy = p
    _thread_local.current_proxy_idx = _PROXY_LIST.index(p) if p in _PROXY_LIST else -1
    return p, f"http://{p}", f"http://{p}"

# 核验期间是否静默代理错误打印（True=不打印，只记录黑名单）
_PROXY_QUIET = True

def _proxy_mark_bad(p, reason=""):
    global _PROXY_FAIL_TOTAL
    with _PROXY_LOCK:
        if p in _PROXY_BAD:
            return  # 已经拉黑过
        _PROXY_BAD.add(p)
        _PROXY_FAIL_TOTAL += 1
        total = len(_PROXY_LIST)
        bad = len(_PROXY_BAD)
        ok = total - bad
    # 核验期间静默：不打印红色拉黑日志，只在最终匹配时显示一次
    if _PROXY_QUIET:
        return
    reason_str = f" ({reason})" if reason else ""
    print(f"  {Color.RED}🔴 代理拉黑: {p}{reason_str} | 池状态: {ok}/{total} 可用 (坏={bad}){Color.RESET}")


