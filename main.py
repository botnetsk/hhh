def proxy_install_for_urllib():
    """给 urllib 安装全局代理（每次随机），返回当前代理字符串"""
    p, http_url, https_url = _proxy_pick()
    proxy_handler = urllib.request.ProxyHandler({
        "http": http_url,
        "https": https_url,
    })
    opener = urllib.request.build_opener(proxy_handler)
    urllib.request.install_opener(opener)
    return p

def proxy_open_for_urllib():
    """不安装全局，返回一个带代理的 opener，返回 (opener, proxy_str)"""
    p, http_url, https_url = _proxy_pick()
    proxy_handler = urllib.request.ProxyHandler({
        "http": http_url,
        "https": https_url,
    })
    return urllib.request.build_opener(proxy_handler), p

def proxy_context_for_http_client():
    """给 http.client 用"""
    p, _, _ = _proxy_pick()
    ip, port = p.split(":")
    return ip, int(port)


