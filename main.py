def _ip_geo_lookup(ip):
    """离线IP地理位置查询（/24 → /16 → /8 三级精确匹配，排除内网）"""
    try:
        import ipaddress as _ip
        ip_obj = _ip.IPv4Address(ip)
        # 排除内网/保留IP
        for priv in [_ip.IPv4Network('10.0.0.0/8'), _ip.IPv4Network('172.16.0.0/12'),
                     _ip.IPv4Network('192.168.0.0/16'), _ip.IPv4Network('127.0.0.0/8'),
                     _ip.IPv4Network('169.254.0.0/16')]:
            if ip_obj in priv:
                return "内网/保留IP"
        # 第1轮: /24 精确匹配（城市级）
        for net_str, loc in _IP_GEO_24.items():
            if ip_obj in _ip.IPv4Network(net_str, strict=False):
                return loc
        # 第2轮: /16 匹配（省级/国家级）
        for net_str, loc in _IP_GEO.items():
            if '/16' not in net_str: continue
            if ip_obj in _ip.IPv4Network(net_str, strict=False):
                return loc
        # 第3轮: /8 兜底
        for net_str, loc in _IP_GEO.items():
            if '/8' not in net_str: continue
            if ip_obj in _ip.IPv4Network(net_str, strict=False):
                return loc
        return "未知 (未识别IP段)"
    except Exception:
        return "未知 (IP解析失败)"


