def _call_api(api_num, name, sfz):
    """带保护壳的接口调用：jitter + 错误分类 + 指数退避 + 熔断 + 统计。
    不改变原速度/线程，正常路径零额外开销。"""
    # 未选中 或 已被剔除, 都直接短路
    if not _api_is_selected(api_num):
        return None, f"{api_name(api_num)}未选中", None, 0
    if _api_is_disabled(api_num):
        return None, f"{api_name(api_num)}已被剔除", None, 0
    # ★ 熔断冷却：连续失败太多，让一下再走
    if _shield_should_trip(api_num):
        time.sleep(_SHIELD_COOLDOWN)
    fn = VERIFY_FUNCS.get(api_num)
    if not fn:
        return None, "未知接口", None, 0

    # ★ 请求抖动：随机 0~30ms，打散扎堆请求（几乎无感）
    _jitter = _rand.random() * 0.030
    time.sleep(_jitter)

    last_msg = ""
    cost_ms = 0
    # 保存最后一次拆包结果
    _result = (None, "", None, 0)

    for attempt in range(1 + _SHIELD_MAX_RETRY):
        t0 = time.time()
        try:
            r = fn(name, sfz)
        except Exception as _e:
            cost_ms = (time.time() - t0) * 1000
            last_msg = f"Exception: {str(_e)[:40]}"
            _SHIELD_STATS[api_num]["retry"] = _SHIELD_STATS[api_num].get("retry", 0) + 1
            if attempt < _SHIELD_MAX_RETRY and _is_retryable(last_msg):
                back = _SHIELD_BACKOFF_BASE * (2 ** attempt)
                time.sleep(back)
                continue
            _result = (None, last_msg, None, cost_ms)
            break
        cost_ms = (time.time() - t0) * 1000
        # 统一拆包
        if isinstance(r, tuple) and len(r) >= 4:
            matched, msg, data, cost = r[0], r[1], r[2], r[3]
            if cost <= 0: cost = cost_ms
        elif isinstance(r, tuple) and len(r) >= 2:
            matched, msg, data, cost = r[0], r[1], (r[2] if len(r) > 2 else None), cost_ms
        else:
            matched, msg, data, cost = None, str(r), None, cost_ms
        _result = (matched, msg, data, cost)
        # ★ 错误分类：可重试且还有次数 → 退避后继续
        if matched is None and attempt < _SHIELD_MAX_RETRY and _is_retryable(msg):
            _SHIELD_STATS[api_num]["retry"] = _SHIELD_STATS[api_num].get("retry", 0) + 1
            back = _SHIELD_BACKOFF_BASE * (2 ** attempt)
            last_msg = msg
            time.sleep(back)
            continue
        last_msg = msg
        break

    matched, msg, data, cost = _result

    # ★ 上报错误/成功（保护壳统计 + 原剔除逻辑）
    _shield_report(api_num, matched, cost, msg)
    if matched is True:
        _api_report_success(api_num)
    elif matched is None:
        _api_report_error(api_num, msg)
    return matched, msg, data, cost

def _probe(api_num, name, sfz):
    m, msg, _, _ = _call_api(api_num, name, sfz)
    return m is not None, msg

def _do_switch(reason):
    global _current_api
    with _api_lock:
        old = _current_api
        active = _api_active_list()
        if not active:
            _current_api = old
        else:
            try:
                idx = active.index(old)
            except ValueError:
                idx = -1
            _current_api = active[(idx + 1) % len(active)]
        new = _current_api
    print(f"  {Color.MAGENTA}{Color.BOLD}🔄 {api_name(old)}不可用({reason})，切换到{api_name(new)}...{Color.RESET}")
    return new

def _switch_and_wait(reason, name, sfz):
    tried = set()
    while len(tried) < 5:
        new_api = _do_switch(reason)
        if new_api in tried: break
        tried.add(new_api)
        ok, msg = _probe(new_api, name, sfz)
        if ok:
            print(f"  {Color.GREEN}✅ {api_name(new_api)}可用，继续核验{Color.RESET}")
            return new_api
        else:
            print(f"  {Color.RED}❌ {api_name(new_api)}也不可用({msg})，继续切换{Color.RESET}")
            reason = msg
    print(f"  {Color.RED}💀 全部接口不可用，等待2秒后重试...{Color.RESET}")
    time.sleep(2)
    return None

