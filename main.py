def _run_batch(name, sfz_list, threads, label=""):
    global total_count, stop_flag, success_card
    total_count = len(sfz_list)
    stop_flag = False
    success_card = ""

    # ★ 清空上轮的错误队列
    with _ERROR_LOCK:
        _ERROR_QUEUE.clear()

    mode_tag = " [并发模式·六接口同时验]" if _concurrent_mode else ""
    delay_tag = f" [延迟={Throttle.delay_ms}ms]" if Throttle.enabled else ""
    print(f"\n{Color.CYAN}第{loop_count}轮 {label}: 共 {total_count} 条, {threads} 线程{mode_tag}{delay_tag}{Color.RESET}")

    # ========== 第一轮：正常核验 ==========
    q = Queue()
    for s in sfz_list: q.put(s)
    for _ in range(threads):
        threading.Thread(target=worker, args=(name, q), daemon=True).start()
    q.join()

    if success_card:
        return True

    # ========== 错误重验轮次 ==========
    _MAX_RETRY_ROUNDS = 2  # 最多再重验2轮（防止死循环）
    for rnd in range(1, _MAX_RETRY_ROUNDS + 1):
        with _ERROR_LOCK:
            err_list = list(_ERROR_QUEUE)
            _ERROR_QUEUE.clear()
        if not err_list:
            break
        # 去重保序
        seen = set(); uniq = []
        for s in err_list:
            if s not in seen:
                seen.add(s); uniq.append(s)
        print(f"\n{Color.YELLOW}🔁 重验轮#{rnd}: {len(uniq)} 条报错/未知记录待重新核验...{Color.RESET}")
        stop_flag = False
        q2 = Queue()
        for s in uniq: q2.put(s)
        # 重验轮用一半线程即可（数量少），至少2个
        rt = max(2, threads // 2)
        for _ in range(min(rt, len(uniq))):
            threading.Thread(target=worker, args=(name, q2), daemon=True).start()
        q2.join()
        if success_card:
            return True
        # 若还有错误，继续下一轮；否则结束
        with _ERROR_LOCK:
            still_err = list(_ERROR_QUEUE)
        if not still_err:
            break

    return False

